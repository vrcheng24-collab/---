def prompt(g):
    p = []
    refs = "；".join(f"@图片{i + 1} 是{ROLE[k] if k in ROLE else '「' + IMG[k].split(' ', 1)[-1] + '」的场景、人物和光影参考'}" for i, k in enumerate(g["refs"]))
    p.append("参考：" + refs + "。" + ("@音频1 是她的歌声。" if "song" in g else ""))
    p.append(FILM + GRADE[g["era"]])
    if g["era"] == "现在" or g["id"] in ("G13", "G15"): p.append(NOW + SCALE)
    if g["era"] in ("回忆", "低谷") or g["id"] == "G13": p.append(PAST)
    if "白模" in g["refs"] or g["era"] == "现在":
        src = "、".join(t for k, t in (("白模", "@{白模} 的实体白模"), ("状态卡", "@{状态卡} 的状态")) if k in g["refs"])
        p.append(FACE.format(src=f"（参考 {src}）" if src else ""))
    if g["era"] == "低谷" or g["id"] in ("G12", "G13"): p.append(DISG)
    if g.get("feel"): p.append("演唱时的表情：" + FEEL[g["feel"]] + "动作是机器的，感情是真的，深情而克制。")
    p.append("画面里的其他人都有自己的动作和反应，不是静止的背景。")
    p.append(f"一共 {len(g['shots'])} 个镜头，按时间硬切：")
    for i, (a, b, s) in enumerate(g["shots"]): p.append(f"镜头{i + 1}（{a:.1f}–{b:.1f} 秒）：{s}")
    if "song" in g:
        p.append("演唱时间：" + "；".join(f"{a:.1f}–{b:.1f} 秒唱「{t}」" for _, a, b, t in lyr(g)) + "。")
        tail = g["song"][1] - g["song"][0]
        if g["dur"] - tail > 1.0: p.append(f"{tail:.1f} 秒以后音频是静音，她不再唱，下颌闭合。")
        p.append(SING)
    else:
        p.append("这一组没有歌声：人物说话只做口型动作，对白后期加字幕；只要现场环境声，不要音乐和人声。生成声音关闭。" if g.get("dlg") else
                 "这一组没有歌声：只要现场环境声（风、雨、火车、机器、人群），不要音乐和人声。")
    if g.get("dlg"): p.append("对白（只出字幕）：" + "／".join(g["dlg"]))
    p.append(NO)
    return at(g, "\n".join(p))

