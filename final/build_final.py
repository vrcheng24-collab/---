def lyr(g):
    a0, cut = g["song"]; out = []
    for lid, a, b, t in LINES:
        if min(b, cut) - max(a, a0) < 0.6: continue
        out.append((lid, max(0.0, a - a0), min(b, cut) - a0, t))
    return out

